const PREFIX = { product: 'p', frontend: 'f', operation: 'o' };

export function buildQuestionBank() {
  const bank = {};
  for (const [position, cats] of Object.entries(TEMPLATES)) {
    bank[position] = [];
    let n = 0;
    for (const category of QUESTION_CATEGORIES) {
      const key = CATEGORY_KEYS[category];
      const items = cats[key] || [];
      items.forEach(([question, keywords, difficulty]) => {
        n += 1;
        bank[position].push({
          id: `${PREFIX[position]}${n}`,
          category,
          question: question.endsWith('？') ? question : `${question}？`,
          keywords,
          difficulty,
        });
      });
    }
  }
  return bank;
}
